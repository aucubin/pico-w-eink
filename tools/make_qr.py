"""Generate src/qr.py: the setup-guide QR code as a bitmap (CPython).

    pip install segno
    python3 tools/make_qr.py [url]

The Pico only draws the stored bitmap, so it needs no QR encoder.
"""
import sys

import segno

url = sys.argv[1] if len(sys.argv) > 1 else "https://github.com/aucubin/pico-w-eink"
qr = segno.make(url, error="m", micro=False)
rows = []
for row in qr.matrix:
    v = 0
    for bit in row:
        v = (v << 1) | (1 if bit else 0)
    rows.append(v)

with open("src/qr.py", "w") as f:
    f.write("# Generated by tools/make_qr.py - do not edit.\n")
    f.write("URL = %r\n" % url)
    f.write("SIZE = %d  # modules per side; each row is a bitmask, MSB = left\n" % len(rows))
    f.write("ROWS = (\n")
    for v in rows:
        f.write("    0x%0*X,\n" % ((len(rows) + 3) // 4, v))
    f.write(")\n")
print("wrote src/qr.py: version %s, %dx%d" % (qr.version, len(rows), len(rows)))
